//! Prints, or checks, the Dart bindings the engine expects.
//!
//! `bindings.dart` in the Flutter app is hand-written, because `dart:ffi` has no
//! generator and ffigen would mean a build dependency on the app's `pubspec` for
//! a file this repository already knows how to describe. The cost of
//! hand-writing is that it can drift from the engine without anybody noticing,
//! which it did: `px_inspect` takes three arguments and the Dart declaration
//! passed two. This binary is the other half of that arrangement — it prints
//! what the declarations should say and it fails when they do not.
//!
//! ```text
//! cargo run --bin px-abi-dump                      # what the declarations should be
//! cargo run --bin px-abi-dump -- --check <file>    # exit 1 if <file> has drifted
//! ```

use pixelsmith_core::ffi_abi::{ENTRY_POINTS, dart_binding_declarations, dart_drift, px_buffer_layout};
use std::process::ExitCode;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("--check") => {
            let Some(path) = args.get(1) else {
                eprintln!("--check needs the path to bindings.dart");
                return ExitCode::from(2);
            };
            let Ok(source) = std::fs::read_to_string(path) else {
                eprintln!("cannot read {path}");
                return ExitCode::from(2);
            };
            let drift = dart_drift(&source);
            if drift.is_empty() {
                println!("{path}: {} entry points match the engine ABI", ENTRY_POINTS.len());
                return ExitCode::SUCCESS;
            }
            eprintln!("{path}: {} declaration(s) do not match the engine:", drift.len());
            for line in drift {
                eprintln!("  {line}");
            }
            ExitCode::FAILURE
        }
        Some(other) => {
            eprintln!("unknown flag: {other}");
            ExitCode::from(2)
        }
        None => {
            println!("// Generated by `cargo run --bin px-abi-dump`. Do not hand-edit.");
            println!("// Engine {}: {} entry points.", pixelsmith_core::ENGINE_VERSION, ENTRY_POINTS.len());
            println!("// Reference output. `cargo run --bin px-abi-dump -- --check` is the gate.");
            println!();
            print!("{}", dart_binding_declarations());
            let layout = px_buffer_layout();
            println!("// PxBuffer: {} bytes, {} byte alignment", layout.size, layout.align);
            for field in &layout.fields {
                println!("//   {:<6} offset {:>2}, size {}", field.name, field.offset, field.size);
            }
            ExitCode::SUCCESS
        }
    }
}