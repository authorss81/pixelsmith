//! Print, and check, the engine's JSON contract.
//!
//! The JSON counterpart to `px-abi-dump`. That binary proves the app's
//! `bindings.dart` matches the engine's C ABI; this one proves the *other* half
//! of the boundary, the JSON that crosses it, which is where five phases of drift
//! accumulated while the ABI check reported "15 entry points match".
//!
//! `scripts/check-json-contract.sh` runs this in three modes:
//!
//!   (no argument)   print the contract, for a human to read
//!   --check FILE    exit non-zero unless FILE's Dart-symbol column covers every
//!                   line the engine emits, and every line in FILE still exists
//!   --print-keys    print only the contract paths, which is what `--check`
//!                   diffs against
//!
//! Both failure directions matter. A field the engine emits with no committed
//! row is drift arriving; a committed row naming a Dart symbol nothing declares
//! is a row that has rotted into a lie, and a check that only looked for the
//! first would go green while that happened.
//!
//! The committed file is `core/contract/json-fields.txt`, in *this* repository.
//! That is the whole reason the check can be a hard gate: the app submodule is
//! `authorss81/shrinkray`, which this pipeline can read and cannot push to, so a
//! check whose answer depended on the app repository's contents could never fail.
//! `docs/AUDIT.md` finding 17, and the note in `verify.sh` section 3b that exists
//! because of it.

use pixelsmith_core::ffi_json::contract;
use std::process::ExitCode;

/// One committed row: a contract path, and the Dart symbol that carries it.
///
/// Three columns, tab-separated, because the middle one is a Dart identifier and
/// the last is prose — neither belongs in a space-separated file.
struct Row {
    path: String,
    dart: String,
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        None => {
            print_contract();
            ExitCode::SUCCESS
        }
        Some("--print-keys") => {
            for line in contract() {
                println!("{line}");
            }
            ExitCode::SUCCESS
        }
        Some("--check") => {
            let Some(path) = args.get(1) else {
                eprintln!("--check needs the path to the committed contract file");
                return ExitCode::from(2);
            };
            check(path)
        }
        Some(other) => {
            eprintln!("unknown flag: {other}");
            ExitCode::from(2)
        }
    }
}

/// The human-readable form: what changed, and which enum it belongs to.
///
/// Grouped by owner because a flat list of 190 dotted paths is a wall, and the
/// question a reader has is "what does `ValidateReport` carry" rather than "what
/// is line 47".
fn print_contract() {
    println!("// Generated by `cargo run --bin px-json-dump`. Do not hand-edit.");
    println!(
        "// Engine {}: {} JSON fields and variants.",
        pixelsmith_core::ENGINE_VERSION,
        contract().len()
    );
    println!(
        "// `scripts/check-json-contract.sh` is the gate; \
         `core/contract/json-fields.txt` is the committed side."
    );
    println!();

    let mut owner = String::new();
    for line in contract() {
        let (this, path) = match line.split_once(['.', ':']) {
            Some(pair) => pair,
            None => (&line[..], &line[..]),
        };
        if *this != owner {
            owner = (*this).to_string();
            println!();
            println!("{owner}");
        }
        println!("  {path}");
    }
}

/// The check itself, and where the two directions are reported separately.
///
/// Reported separately because the two failures need different people: a missing
/// row means the engine changed and the app has not been told, while a stale row
/// means somebody renamed a Dart field and did not notice the contract file had
/// stopped being true.
fn check(path: &str) -> ExitCode {
    let Ok(source) = std::fs::read_to_string(path) else {
        eprintln!("cannot read {path}");
        return ExitCode::from(2);
    };
    let rows = parse(&source);
    let engine = contract();

    // Direction one: the engine emits a field the committed file does not know
    // about. This is drift arriving, and it is the failure that has been silent
    // for five phases.
    let mut unrecorded: Vec<&String> = engine
        .iter()
        .filter(|line| !rows.iter().any(|row| row.path == **line))
        .collect();

    // Direction two: the committed file names a contract path the engine does
    // not have. A renamed or removed field, or a row typed from memory.
    let mut stale: Vec<&Row> = rows
        .iter()
        .filter(|row| !engine.iter().any(|line| line == &row.path))
        .collect();

    // Direction three, and the one that makes the file mean something: a row
    // with no Dart symbol. A row that names nothing is indistinguishable from a
    // row nobody wrote, which is how the drift got here in the first place.
    let mut unmodelled: Vec<&Row> = rows
        .iter()
        .filter(|row| row.dart.is_empty() || row.dart == "-")
        .collect();

    unrecorded.sort();
    stale.sort_by(|a, b| a.path.cmp(&b.path));
    unmodelled.sort_by(|a, b| a.path.cmp(&b.path));

    for line in &unrecorded {
        eprintln!(
            "  the engine emits {line}, which {path} does not record.\n    \
             add a row naming the Dart symbol that carries it, and land the \
             matching change in the app repository."
        );
    }
    for row in &stale {
        eprintln!(
            "  {path} records {}, which the engine no longer emits.\n    \
             the row has rotted: rename or delete it.",
            row.path
        );
    }
    for row in &unmodelled {
        eprintln!(
            "  {path} records {} with no Dart symbol.\n    \
             every row must name the Dart member that carries the field; a row \
             with nothing after the tab is how this drifted in the first place.",
            row.path
        );
    }

    let failures = unrecorded.len() + stale.len() + unmodelled.len();
    if failures == 0 {
        println!(
            "JSON CONTRACT: {} fields and variants, all recorded in {path}",
            engine.len()
        );
        return ExitCode::SUCCESS;
    }
    eprintln!(
        "JSON CONTRACT: {} unrecorded, {} stale, {} unmodelled (of {} lines)",
        unrecorded.len(),
        stale.len(),
        unmodelled.len(),
        rows.len()
    );
    ExitCode::FAILURE
}

/// Parse the committed file.
///
/// Comments and blank lines are skipped so the file can explain itself, which it
/// has to: it is the only place the engine's contract and the app's models are
/// written next to each other, and an unexplained table of 190 rows is one
/// nobody will maintain.
fn parse(source: &str) -> Vec<Row> {
    source
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| {
            let mut parts = line.split('\t');
            let path = parts.next().unwrap_or_default().to_string();
            let dart = parts.next().unwrap_or_default().trim().to_string();
            Row { path, dart }
        })
        .collect()
}
